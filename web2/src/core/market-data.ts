// Generate realistic synthetic OHLCV candles
function generateCandles(basePrice: number, count = 40): CandleData[] {
  const candles: CandleData[] = [];
  let currentPrice = basePrice * 0.88;
  const now = new Date();
  
  for (let i = count - 1; i >= 0; i--) {
    const d = new Date(now);
    d.setDate(d.getDate() - i);
    const dateStr = d.toISOString().split('T')[0];
    
    const delta = (Math.random() - 0.48) * (currentPrice * 0.024);
    const open = Number(currentPrice.toFixed(2));
    const close = Number(Math.max(1, open + delta).toFixed(2));
    const high = Number((Math.max(open, close) + Math.random() * (open * 0.015)).toFixed(2));
    const low = Number((Math.min(open, close) - Math.random() * (open * 0.015)).toFixed(2));
    const volume = Math.floor(200000 + Math.random() * 800000);
    
    candles.push({
      time: dateStr,
      open,
      high,
      low,
      close,
      volume,
    });
    currentPrice = close;
  }
  return candles;
}

function generateSparkline(candles: CandleData[]): number[] {
  return candles.slice(-14).map((c) => c.close);
}

